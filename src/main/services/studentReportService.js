function renderTable(headers, rows, t) {
  if (!rows || rows.length === 0) return `<p class="empty">${esc(t.empty)}</p>`
  const head = headers.map(h => `<th>${esc(h)}</th>`).join('')
  const body = rows
    .map(cells => `<tr>${cells.map(cell => `<td>${cell}</td>`).join('')}</tr>`)
    .join('')
  return `<table><thead><tr>${head}</tr></thead><tbody>${body}</tbody></table>`
}

function languageLabel(value) {
  return value === 'M' ? 'male' : value === 'F' ? 'female' : null
}

// Prints every attribute it is given. A value that is not on file shows the
// report language's N/A token instead of the line disappearing, so the sheet
// records what the student file is missing. Values are escaped here.
function fieldsOf(pairs, na) {
  return pairs.map(([label, value]) => {
    const text = value === null || value === undefined ? '' : String(value).trim()
    const shown = text === '' ? `<span class="missing">${esc(na)}</span>` : esc(text)
    return `<div class="field"><span class="k">${esc(label)}</span><span class="v">${shown}</span></div>`
  })
}

