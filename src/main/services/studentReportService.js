function esc(value) {
  return String(value === null || value === undefined ? '' : value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function dash(value) {
  if (value === null || value === undefined) return '—'
  const text = String(value).trim()
  return text ? esc(text) : '—'
}

function fmtDate(value) {
  if (!value) return '—'
  const d = value instanceof Date ? value : new Date(value)
  if (isNaN(d.getTime())) return dash(value)
  const pad = n => String(n).padStart(2, '0')
  return `${pad(d.getDate())}/${pad(d.getMonth() + 1)}/${d.getFullYear()}`
}

function fmtTime(value) {
  if (!value) return ''
  const text = String(value)
  const m = text.match(/(\d{2}):(\d{2})/)
  return m ? `${m[1]}:${m[2]}` : text
}

function fmtDateTime(value) {
  if (!value) return '—'
  const d = value instanceof Date ? value : new Date(value)
  if (isNaN(d.getTime())) return dash(value)
  return `${fmtDate(d)} ${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`
}

// Same as fmtDate, but raw instead of an em dash: the details grid prints a
// language-specific "N/A" marker when a value is not on file.
function dateText(value) {
  if (!value) return ''
  const d = value instanceof Date ? value : new Date(value)
  if (isNaN(d.getTime())) return String(value).trim()
  const pad = n => String(n).padStart(2, '0')
  return `${pad(d.getDate())}/${pad(d.getMonth() + 1)}/${d.getFullYear()}`
}

// The printable student file is part of consulting a student, which Directors
// and Admins both do: an Admin oversees every role and must not lose a page a
// Director can open. Writers of the record itself stay restricted.
async function requireReportReader(userId) {
  const id = parseInt(userId, 10)
  if (!id) throw new Error('Not allowed: you must be signed in.')

  const res = await query(
    `SELECT 1 FROM "user" u
     JOIN "role" r ON r.role_id = u.role_id
     WHERE u.user_id = $1 AND u.is_active = true AND r.role_code IN ('DIRECTOR', 'ADMIN')
     LIMIT 1`,
    [id]
  )
  if (res.rowCount === 0) {
    throw new Error('Not allowed: only a Director or an Administrator can generate a student report.')
  }
  return id
}

